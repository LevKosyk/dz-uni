VYRAZY = {
    # 1. Час ГГ:ХХ від 00:00 до 23:59
    "chas": r"^([01]\d|2[0-3]):[0-5]\d$",
    # пояснення: спершу години від 00 до 19 або від 20 до 23, далі двокрапка й хвилини від 00 до 59

    # 2. Дата дд.мм.рррр, місяць від 01 до 12 
    "data": r"^\d{2}\.(0[1-9]|1[0-2])\.\d{4}$",
    # пояснення: дві цифри дня, місяць 01–09 або 10–12, ще одна крапка й чотири цифри року 

    # 3. IP-адреса: чотири числа по 1–3 цифри через крапку
    "ip": r"^\d{1,3}(\.\d{1,3}){3}$",
    # пояснення: спершу число від 1 до 3 цифр, потім тричі крапка й число від 1 до 3 цифр

    # 4. Імʼя змінної Python: латинська літера або _, далі літери, цифри, _
    "identyfikator": r"^[A-Za-z_][A-Za-z0-9_]*$",
    # пояснення: перший символ - латинська літера або _, далі скільки завгодно латинських літер, цифр і _ на кінці

    # 5. Лише великі латинські літери, від 3 до 8
    "velyki": r"^[A-Z]{3,8}$",
    # пояснення: [A-Z] великі латинські літери, {3,8} від 3 до 8 штук

    # 6. Усі слова, довші за 8 літер (перевіряється через re.findall)
    "dovgi_slova": r"\b\w{9,}\b",
    # пояснення: \w{9,} 9 і більше літер підряд, а \b з обох боків означає межі слова, щоб брати слово цілком
}

